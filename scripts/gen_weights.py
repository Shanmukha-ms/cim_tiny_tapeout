# ---------------------------------------------------------------------------
# Verification helper: compute expected output for a test vector
# ---------------------------------------------------------------------------

def predict(x: np.ndarray, w_bin: np.ndarray, thresh: int) -> int:
    """
    Software BNN inference — matches the Verilog exactly.
    x     : binary input vector {0,1}^n
    w_bin : binary weight vector {0,1}^n
    thresh: integer threshold
    """
    match = ~(np.array(x, dtype=np.uint8) ^ np.array(w_bin, dtype=np.uint8)) & 1
    return int(np.sum(match) >= thresh)


def generate_test_vectors(w_bin: np.ndarray, thresh: int, n_samples: int = 16) -> str:
    """
    Generate expected-output table for manual testbench population.
    """
    n = len(w_bin)
    rng = np.random.default_rng(42)
    lines = ["// x (hex)  expected_y  popcount"]
    for _ in range(n_samples):
        x = rng.integers(0, 2, size=n)
        y = predict(x, w_bin, thresh)
        x_int = int(''.join(str(b) for b in reversed(x)), 2)
        pc = int(np.sum(~(x ^ w_bin) & 1))
        lines.append(f"// 8'h{x_int:02X}      {y}           {pc}")
    return "\n".join(lines)


