#!/usr/bin/env python3
"""
gen_weights.py — Convert trained float weights to Verilog BNN localparam strings.

Workflow:
  1. Train a full-precision model externally (PyTorch / sklearn / etc.)
  2. Extract the weight vector for each neuron
  3. Run this script to produce copy-pasteable Verilog constants
  4. Paste output into your RTL module's localparam section

Usage:
  python3 gen_weights.py

Or import and call generate_verilog_params() from your training script.
"""

import numpy as np
from typing import List, Tuple


# ---------------------------------------------------------------------------
# Core conversion functions
# ---------------------------------------------------------------------------

def binarize(weights: np.ndarray) -> np.ndarray:
    """
    Threshold float weights to {0, 1}.
    Convention: positive  →  1  (agrees with +1 in {-1,+1} BNN)
                non-positive → 0  (maps -1 to 0 for XNOR encoding)
    """
    return (weights > 0).astype(int)


def popcount(bits: np.ndarray) -> int:
    return int(np.sum(bits))


def optimal_threshold(n_inputs: int) -> int:
    """
    Default threshold = ceil(n/2).  Fires when strict majority of inputs match.
    Tune per neuron based on validation accuracy.
    """
    return (n_inputs + 1) // 2


def weights_to_verilog_param(
    weights_bin: np.ndarray,
    name: str = "W",
    n_bits: int = 8
) -> str:
    """
    Convert a binary weight array to a Verilog localparam literal.

    weights_bin[0] → x[0] (LSB), weights_bin[n-1] → x[n-1] (MSB).
    Verilog bit-string is written MSB-first (left to right).
    """
    if len(weights_bin) != n_bits:
        raise ValueError(f"Expected {n_bits} weights, got {len(weights_bin)}")
    # Reverse: MSB (index n-1) appears leftmost in Verilog string
    bits_str = ''.join(str(int(b)) for b in reversed(weights_bin))
    return f"localparam [{n_bits-1}:0] {name} = {n_bits}'b{bits_str};"


def threshold_to_verilog_param(thresh: int, name: str = "THRESH") -> str:
    n_bits = int(np.ceil(np.log2(thresh + 1))) + 1  # enough bits
    n_bits = max(n_bits, 4)                          # at least 4 for readability
    return f"localparam [{n_bits-1}:0] {name} = {n_bits}'d{thresh};"


def generate_verilog_params(
    neuron_weights: List[np.ndarray],
    thresholds: List[int] = None,
    weight_names: List[str] = None,
    threshold_names: List[str] = None,
) -> str:
    """
    Generate Verilog localparam declarations for one or more neurons.

    Args:
        neuron_weights  : list of 1-D float or binary arrays, one per neuron
        thresholds      : optional per-neuron integer thresholds;
                          defaults to ceil(n/2) for each
        weight_names    : optional names e.g. ["W0","W1"]
        threshold_names : optional names e.g. ["T0","T1"]

    Returns:
        Multi-line string ready to paste into Verilog.
    """
    n = len(neuron_weights)
    n_inputs = len(neuron_weights[0])

    if thresholds is None:
        thresholds = [optimal_threshold(n_inputs)] * n
    if weight_names is None:
        weight_names = [f"W{i}" if n > 1 else "W" for i in range(n)]
    if threshold_names is None:
        threshold_names = [f"T{i}" if n > 1 else "THRESH" for i in range(n)]

    lines = ["// Auto-generated by gen_weights.py — do not edit manually", ""]
    for i, (w_raw, thresh, wname, tname) in enumerate(
            zip(neuron_weights, thresholds, weight_names, threshold_names)):
        w_bin = binarize(np.asarray(w_raw, dtype=float))
        lines.append(f"// Neuron {i}: {popcount(w_bin)}/{n_inputs} positive weights, "
                     f"threshold={thresh}")
        lines.append(weights_to_verilog_param(w_bin, wname, n_inputs))
        lines.append(threshold_to_verilog_param(thresh, tname))
        lines.append("")

    return "\n".join(lines)


